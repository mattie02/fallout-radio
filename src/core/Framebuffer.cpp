void Framebuffer::clear() { std::memset(buf_, 0, sizeof(buf_)); }

void Framebuffer::invert() {
    for (auto& b : buf_) b = static_cast<uint8_t>(~b);
}

void Framebuffer::setPixel(int x, int y, bool on) {
    if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return;
    uint8_t& b = buf_[x + (y / 8) * kWidth];
    const uint8_t mask = static_cast<uint8_t>(1u << (y % 8));
    b = on ? (b | mask) : (b & ~mask);
}

bool Framebuffer::getPixel(int x, int y) const {
    if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return false;
    return buf_[x + (y / 8) * kWidth] & (1u << (y % 8));
}

void Framebuffer::hLine(int x, int y, int w) { fillRect(x, y, w, 1); }

void Framebuffer::vLine(int x, int y, int h) { fillRect(x, y, 1, h); }

void Framebuffer::fillRect(int x, int y, int w, int h, bool on) {
    for (int yy = y; yy < y + h; ++yy)
        for (int xx = x; xx < x + w; ++xx) setPixel(xx, yy, on);
}

void Framebuffer::drawChar(int x, int y, char c, int scale) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    if (c < kFirstChar || c > kLastChar) c = '?';
    const uint8_t* glyph = kFont[c - kFirstChar];
    for (int col = 0; col < 5; ++col)
        for (int row = 0; row < 8; ++row)
            if (glyph[col] & (1u << row))
                fillRect(x + col * scale, y + row * scale, scale, scale);
}

int Framebuffer::drawText(int x, int y, const char* text, int scale) {
    for (; *text; ++text) {
        drawChar(x, y, *text, scale);
        x += kCharWidth * scale;
    }
    return x;
}

int Framebuffer::textWidth(const char* text, int scale) {
    return static_cast<int>(std::strlen(text)) * kCharWidth * scale;
}

